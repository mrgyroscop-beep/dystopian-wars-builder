import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const corpusPath = path.resolve("worker/rules-corpus.generated.ts");
const translationsPath = path.resolve("data/generated/glossary-translations.ru.json");
const migrationPath = path.resolve("migrations/0005_russian_glossary_seed.sql");

const corpusSource = await readFile(corpusPath, "utf8");
const rules = JSON.parse(corpusSource.replace(/^.*?= /s, "").replace(/ as const;\s*$/u, ""));
const translations = JSON.parse(await readFile(translationsPath, "utf8"));
const bySourceTitle = new Map();
for (const translation of translations) {
  const entries = bySourceTitle.get(translation.sourceTitle) ?? [];
  entries.push(translation);
  bySourceTitle.set(translation.sourceTitle, entries);
}
const qualityIssues = [];

if (translations.length !== rules.length) {
  throw new Error(`Expected ${rules.length} translations, received ${translations.length} rows.`);
}

const statements = rules.map((rule) => {
  const translation = bySourceTitle.get(rule.title)?.shift();
  if (
    !translation ||
    translation.sourceTitle !== rule.title ||
    typeof translation.title !== "string" ||
    !translation.title.trim() ||
    typeof translation.text !== "string" ||
    !translation.text.trim()
  ) {
    throw new Error(`Translation ${rule.id} does not match the current English corpus.`);
  }
  if (!/[А-ЯЁа-яё]/u.test(`${translation.title} ${translation.text}`)) {
    qualityIssues.push(`${rule.id}: Russian text contains no Cyrillic characters`);
  }
  const sourceMarkers = extractRuleMarkers(rule.text);
  const translatedMarkers = extractRuleMarkers(translation.text);
  if (sourceMarkers.join("|") !== translatedMarkers.join("|")) {
    qualityIssues.push(
      `${rule.id}: numeric/X markers changed (${sourceMarkers.join(", ")} -> ${translatedMarkers.join(", ")})`,
    );
  }
  const sourceHash = createHash("sha256").update(`${rule.title}\n${rule.text}`).digest("hex");
  return `INSERT INTO rule_translations (rule_id, language, source_title, source_hash, title, text) VALUES (${[
    rule.id,
    "ru",
    rule.title,
    sourceHash,
    translation.title.trim(),
    translation.text.trim(),
  ]
    .map(sqlString)
    .join(", ")});`;
});

if (qualityIssues.length > 0) {
  console.warn(
    `Russian glossary quality checks reported legacy translation drift:\n${qualityIssues.join("\n")}`,
  );
}

const migration = [
  "-- Generated by scripts/assistant/build-russian-glossary-migration.mjs.",
  "-- Do not edit manually; update the versioned translation corpus and regenerate.",
  "",
  ...statements,
  "",
].join("\n");

await writeFile(migrationPath, migration, "utf8");
console.log(`Russian glossary migration generated: ${statements.length} rows.`);

function sqlString(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function extractRuleMarkers(value) {
  return value.match(/\d+(?:[.,]\d+)?|\bX\b/gu) ?? [];
}
