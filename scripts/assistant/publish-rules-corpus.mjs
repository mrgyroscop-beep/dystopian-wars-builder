import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";

const projectRoot = path.resolve(import.meta.dirname, "..", "..");
const catalogRoot = path.join(projectRoot, "public", "catalog");
const index = JSON.parse(fs.readFileSync(path.join(catalogRoot, "factions.json"), "utf8"));
const glossaryPages = JSON.parse(
  fs.readFileSync(path.join(import.meta.dirname, "rules-glossary-pages.json"), "utf8"),
);
const glossaryOverrides = JSON.parse(
  fs.readFileSync(path.join(import.meta.dirname, "rules-glossary-overrides.json"), "utf8"),
).entries;
const translations = JSON.parse(
  fs.readFileSync(
    path.join(projectRoot, "data", "generated", "glossary-translations.ru.json"),
    "utf8",
  ),
);
const translationsById = new Map(translations.map((translation) => [translation.id, translation]));
const uniqueRules = new Map();

for (const faction of Object.values(index.factions)) {
  const catalog = JSON.parse(
    zlib.gunzipSync(fs.readFileSync(path.join(catalogRoot, faction.path))).toString("utf8"),
  );
  for (const entity of Object.values(catalog.entities)) {
    if (entity.kind !== "Rule") continue;
    const sourceTitle = entity.label?.plainText?.trim();
    const sourceText = entity.description?.plainText?.trim();
    const documentPath = entity.provenance?.documentPath;
    const glossaryOverride =
      documentPath === "Rules Glossary.cat" && sourceTitle
        ? glossaryOverrides[sourceTitle]
        : undefined;
    const title = glossaryOverride?.title ?? sourceTitle;
    const text = glossaryOverride?.text ?? sourceText;
    if (!title || !text) continue;
    const key = `${title}\n${text}`;
    const current = uniqueRules.get(key);
    if (current) {
      current.factions.add(faction.label);
      if (documentPath) current.documents.add(documentPath);
    } else {
      uniqueRules.set(key, {
        title,
        text,
        factions: new Set([faction.label]),
        documents: new Set(documentPath ? [documentPath] : []),
      });
    }
  }
}

const englishRules = [...uniqueRules.values()]
  .map((rule, index) => ({
    id: `R${index + 1}`,
    title: rule.title,
    text: rule.text,
    factions: [...rule.factions].sort(),
    page: rule.documents.has("Rules Glossary.cat") ? (glossaryPages[rule.title] ?? null) : null,
  }))
  .sort((left, right) => left.title.localeCompare(right.title, "en"));
const rules = englishRules.map((rule) => {
  const translation = translationsById.get(rule.id);
  if (!translation || translation.sourceTitle !== rule.title) {
    throw new Error(`Stored Russian translation ${rule.id} does not match ${rule.title}.`);
  }
  return { ...rule, translation: { ...translation, language: "ru" } };
});
if (rules.length !== translationsById.size) {
  throw new Error(
    `Expected one stored Russian translation per rule: ${rules.length} rules, ${translationsById.size} translations.`,
  );
}
const output = `// Generated by scripts/assistant/publish-rules-corpus.mjs.\nexport const rulesCorpus = ${JSON.stringify(rules)} as const;\n`;
const outputPath = path.join(projectRoot, "worker", "rules-corpus.generated.ts");
fs.writeFileSync(outputPath, output, "utf8");
console.log(`Published ${rules.length} assistant rule sources.`);
